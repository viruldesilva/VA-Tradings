-- Migration 001: move supplier_price / supplier_url out of products
--
-- ONLY run this if you already created the tables from an earlier script.
-- Then run supabase/schema.sql afterwards (it adds RLS, settings, storage...).
-- Safe to re-run.
-- =============================================================================

do $$
declare
  id_type text;
begin
  select data_type into id_type
  from information_schema.columns
  where table_schema = 'public' and table_name = 'products' and column_name = 'id';

  if id_type is null then
    raise exception 'public.products does not exist. Skip this migration and just run schema.sql.';
  end if;

  if id_type <> 'uuid' then
    raise exception 'public.products.id is "%", expected uuid. Stop here and share your existing table definitions.', id_type;
  end if;
end $$;

-- 1. Private table for supplier info
create table if not exists public.product_private (
  product_id     uuid primary key references public.products (id) on delete cascade,
  supplier_price numeric(12, 2) check (supplier_price >= 0),
  supplier_url   text
);

-- 2. Copy existing supplier data, then drop the public columns
do $$
declare
  has_price boolean;
  has_url   boolean;
begin
  select
    bool_or(column_name = 'supplier_price'),
    bool_or(column_name = 'supplier_url')
  into has_price, has_url
  from information_schema.columns
  where table_schema = 'public' and table_name = 'products';

  if coalesce(has_price, false) or coalesce(has_url, false) then
    execute format(
      'insert into public.product_private (product_id, supplier_price, supplier_url)
       select id, %s, %s from public.products
       on conflict (product_id) do update
         set supplier_price = excluded.supplier_price,
             supplier_url   = excluded.supplier_url',
      case when has_price then 'supplier_price::numeric(12,2)' else 'null' end,
      case when has_url   then 'supplier_url::text'            else 'null' end
    );

    alter table public.products drop column if exists supplier_price;
    alter table public.products drop column if exists supplier_url;
    raise notice 'Moved supplier fields into product_private.';
  else
    raise notice 'products has no supplier columns; nothing to move.';
  end if;
end $$;

-- 3. Make sure every product has a private row (keeps admin joins simple)
insert into public.product_private (product_id)
select id from public.products
on conflict (product_id) do nothing;

-- 4. Add columns the new app expects, if the earlier script didn't have them.
--    (Only columns with safe defaults are added automatically.)
alter table public.products
  add column if not exists description text not null default '',
  add column if not exists in_stock    boolean not null default true,
  add column if not exists is_visible  boolean not null default true,
  add column if not exists images      text[] not null default '{}',
  add column if not exists created_at  timestamptz not null default now();

