-- -----------------------------------------------------------------------------
-- Tables
-- -----------------------------------------------------------------------------

create table if not exists public.categories (
  id   uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null unique
);

create table if not exists public.products (
  id          uuid primary key default gen_random_uuid(),
  name        text not null,
  slug        text not null unique,
  description text not null default '',
  price       numeric(12, 2) not null check (price >= 0),
  in_stock    boolean not null default true,
  is_visible  boolean not null default true,
  images      text[] not null default '{}',
  warranty_months integer check (warranty_months between 0 and 120),
  condition   text not null default 'new'
              check (condition in ('new', 'used', 'refurbished')),
  category_id uuid references public.categories (id) on delete set null,
  created_at  timestamptz not null default now()
);

-- Added later: bring existing products tables up to date.
alter table public.products add column if not exists brand text;
create index if not exists products_brand_idx on public.products (lower(brand));
alter table public.products
  add column if not exists warranty_months integer
    check (warranty_months between 0 and 120);
alter table public.products
  add column if not exists condition text not null default 'new'
    check (condition in ('new', 'used', 'refurbished'));

-- Supplier details live in their own table so the public can never read them.
create table if not exists public.product_private (
  product_id     uuid primary key references public.products (id) on delete cascade,
  supplier_price numeric(12, 2) check (supplier_price >= 0),
  supplier_url   text
);

create table if not exists public.orders (
  id             uuid primary key default gen_random_uuid(),
  order_no       bigint generated by default as identity (start with 1001) unique,
  customer_name  text not null,
  phone          text not null,
  address        text not null,
  city           text not null,
  notes          text,
  subtotal       numeric(12, 2) not null check (subtotal >= 0),
  delivery_fee   numeric(12, 2) not null default 0 check (delivery_fee >= 0),
  total          numeric(12, 2) not null check (total >= 0),
  payment_method text not null check (payment_method in ('cod', 'payhere')),
  payment_status text not null default 'pending'
                 check (payment_status in ('pending', 'paid', 'failed')),
  status         text not null default 'new'
                 check (status in ('new', 'bought', 'shipped', 'delivered', 'cancelled')),
  tracking_no    text,
  -- Random secret in the customer's confirmation link, so orders can't be
  -- viewed by guessing sequential order numbers.
  public_token   uuid not null default gen_random_uuid(),
  created_at     timestamptz not null default now()
);

-- (for databases created before public_token existed)
alter table public.orders
  add column if not exists public_token uuid not null default gen_random_uuid();

create table if not exists public.order_items (
  id           uuid primary key default gen_random_uuid(),
  order_id     uuid not null references public.orders (id) on delete cascade,
  -- Nullable so deleting a product later doesn't delete order history.
  product_id   uuid references public.products (id) on delete set null,
  product_name text not null,
  qty          integer not null check (qty > 0),
  price        numeric(12, 2) not null check (price >= 0),
  -- Supplier cost when the order was placed (for accurate profit reports).
  supplier_price numeric(12, 2)
);

alter table public.order_items
  add column if not exists supplier_price numeric(12, 2);

-- Single-row settings table (id is always 1).
create table if not exists public.settings (
  id              integer primary key default 1 check (id = 1),
  delivery_fee    numeric(12, 2) not null default 0 check (delivery_fee >= 0),
  shop_phone      text,
  whatsapp_number text
);

insert into public.settings (id, delivery_fee)
values (1, 400)
on conflict (id) do nothing;

-- Which auth users are admins. Supabase allows sign-ups through the API by
-- default, so "any logged-in user" is NOT a safe admin check on its own.
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users (id) on delete cascade
);

-- -----------------------------------------------------------------------------
-- Table privileges
-- Newer Supabase projects don't auto-grant API access to tables created in the
-- SQL editor, so grant it explicitly. Row Level Security (below) still decides
-- which ROWS each role can see; these grants only allow the role to ask.
-- -----------------------------------------------------------------------------

grant usage on schema public to anon, authenticated, service_role;

-- Visitors: read-only access to the public shop tables only.
grant select on public.categories, public.products, public.settings to anon;

-- Logged-in users: RLS limits everything to admins (see is_admin()).
grant select, insert, update, delete on all tables in schema public to authenticated;

-- Server-side code (orders API, PayHere callback) uses the service role.
grant all on all tables in schema public to service_role;
grant usage, select on all sequences in schema public to authenticated, service_role;

-- -----------------------------------------------------------------------------
-- Indexes
-- -----------------------------------------------------------------------------

create index if not exists products_category_id_idx on public.products (category_id);
create index if not exists products_created_at_idx  on public.products (created_at desc);
create index if not exists orders_created_at_idx    on public.orders (created_at desc);
create index if not exists orders_status_idx        on public.orders (status);
create index if not exists order_items_order_id_idx on public.order_items (order_id);

-- -----------------------------------------------------------------------------
-- Admin check used by every policy
-- -----------------------------------------------------------------------------

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users where user_id = auth.uid()
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

-- -----------------------------------------------------------------------------
-- Row Level Security
-- Customers never write to the DB directly: orders are inserted by a server
-- route with the service-role key (which bypasses RLS).
-- -----------------------------------------------------------------------------

alter table public.categories      enable row level security;
alter table public.products        enable row level security;
alter table public.product_private enable row level security;
alter table public.orders          enable row level security;
alter table public.order_items     enable row level security;
alter table public.settings        enable row level security;
alter table public.admin_users     enable row level security;

-- categories: public read, admin write
drop policy if exists "categories_public_read" on public.categories;
create policy "categories_public_read" on public.categories
  for select to anon, authenticated using (true);

drop policy if exists "categories_admin_all" on public.categories;
create policy "categories_admin_all" on public.categories
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- products: public reads visible products only, admin does everything
drop policy if exists "products_public_read" on public.products;
create policy "products_public_read" on public.products
  for select to anon, authenticated using (is_visible);

drop policy if exists "products_admin_all" on public.products;
create policy "products_admin_all" on public.products
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- product_private: admin only. Also revoke table privileges from anon as a
-- second layer, so even a policy mistake can't expose supplier data.
revoke all on public.product_private from anon;

drop policy if exists "product_private_admin_all" on public.product_private;
create policy "product_private_admin_all" on public.product_private
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- orders / order_items: admin only
revoke all on public.orders, public.order_items from anon;

drop policy if exists "orders_admin_all" on public.orders;
create policy "orders_admin_all" on public.orders
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "order_items_admin_all" on public.order_items;
create policy "order_items_admin_all" on public.order_items
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- settings: public read, admin update
drop policy if exists "settings_public_read" on public.settings;
create policy "settings_public_read" on public.settings
  for select to anon, authenticated using (true);

drop policy if exists "settings_admin_update" on public.settings;
create policy "settings_admin_update" on public.settings
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

-- admin_users: an admin may see the list; nobody writes via the API
-- (add admins in the SQL editor, see the bottom of this file).
revoke all on public.admin_users from anon;

drop policy if exists "admin_users_admin_read" on public.admin_users;
create policy "admin_users_admin_read" on public.admin_users
  for select to authenticated using (public.is_admin());

-- -----------------------------------------------------------------------------
-- Storage: product-images bucket (public read, admin write)
-- Public buckets serve files by URL without a select policy.
-- -----------------------------------------------------------------------------

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'product-images',
  'product-images',
  true,
  5242880, -- 5 MB
  array['image/jpeg', 'image/png', 'image/webp', 'image/avif']
)
on conflict (id) do update set public = true;

drop policy if exists "product_images_admin_select" on storage.objects;
create policy "product_images_admin_select" on storage.objects
  for select to authenticated
  using (bucket_id = 'product-images' and public.is_admin());

drop policy if exists "product_images_admin_insert" on storage.objects;
create policy "product_images_admin_insert" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'product-images' and public.is_admin());

drop policy if exists "product_images_admin_update" on storage.objects;
create policy "product_images_admin_update" on storage.objects
  for update to authenticated
  using (bucket_id = 'product-images' and public.is_admin());

drop policy if exists "product_images_admin_delete" on storage.objects;
create policy "product_images_admin_delete" on storage.objects
  for delete to authenticated
  using (bucket_id = 'product-images' and public.is_admin());

